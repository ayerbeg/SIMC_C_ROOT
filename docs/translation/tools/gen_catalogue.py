#!/usr/bin/env python3
"""Generate docs/translation/06_catalogue.md: the catalogue of every Fortran bug, quirk and deliberate deviation, in one
uniform table, from the per-class tables of docs/FORTRAN_DIFFERENCES.md (sections 2-6, the single source that the code
comments and the tests cite), plus a cross-check against the finding ids of project_control/DECISIONS.md.

Usage: gen_catalogue.py [--differences FILE] [--decisions FILE] [--out FILE]
Defaults: docs/FORTRAN_DIFFERENCES.md, $SIMC_DECISIONS or <source>/../../project_control/DECISIONS.md (the project
layout), docs/translation/06_catalogue.md.
Do not edit 06_catalogue.md by hand: edit FORTRAN_DIFFERENCES.md and re-run this script.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, "..", "..", ".."))

# section heading prefix -> (class, column roles). Roles: id, loc, beh, def, eff, extra
SECTIONS = [
    ("## 2.", "a"), ("### Class a-np", "a-np"), ("## 3.", "c"), ("## 4.", "b"), ("## 5.", "d"), ("## 6.", "dev"),
]
CLASS_TEXT = {
    "a": "clear Fortran bug: corrected by default, Fortran kept with --fortran-compat",
    "a-np": "clear bug in a path that was not ported (fix when porting)",
    "b": "ambiguous, maybe intended: Fortran kept in both modes (expert list)",
    "c": "open question with the user (acceptance mode): Fortran kept in both modes",
    "d": "faithful Fortran behaviour, not a bug: kept in both modes",
    "dev": "deliberate design deviation of SIMC++ (not a Fortran bug): SIMC++ behaviour in both modes",
}


def split_row(line):
    """Split a Markdown table row on '|' outside code spans."""
    cells, cur, tick = [], "", False
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    i = 0
    while i < len(s):
        c = s[i]
        if c == "`":
            tick = not tick
        if c == "\\" and i + 1 < len(s) and s[i + 1] == "|":
            cur += "\\|"
            i += 2
            continue
        if c == "|" and tick:
            cur += "\\|"   # GitHub tables need the escape even inside a code span (P15.D5)
            i += 1
            continue
        if c == "|" and not tick:
            cells.append(cur.strip())
            cur = ""
        else:
            cur += c
        i += 1
    cells.append(cur.strip())
    return cells


def parse(diff_path):
    text = open(diff_path, encoding="utf-8").read().split("\n")
    rows, cls, header = [], None, None
    for line in text:
        if line.startswith("#"):
            cls = None
            for pre, c in SECTIONS:
                if line.startswith(pre):
                    cls = c
            header = None
            continue
        if cls is None or not line.startswith("|"):
            continue
        cells = split_row(line)
        if header is None:
            header = [h.lower() for h in cells]
            continue
        if set(line.replace("|", "").strip()) <= set("-: "):
            continue
        d = dict(zip(header, cells))
        rows.append((cls, header, d))
    return rows


def norm(cls, header, d):
    g = lambda *keys: next((d[k] for k in d if any(k.startswith(x) for x in keys)), "")
    rid, loc = g("id"), g("fortran")
    if cls == "a":
        return rid, loc, g("original", "bug"), g("c++ default", "c++ now"), "Fortran (original behaviour)", \
            g("effect", "to do"), g("test")
    if cls == "a-np":
        return rid, loc, g("bug"), g("c++ now"), "-", g("to do"), ""
    if cls == "c":
        return rid, loc, g("behaviour"), "Fortran kept", "Fortran kept", g("effect"), g("marker")
    if cls == "b":
        return rid, loc, g("behaviour"), "Fortran kept", "Fortran kept", g("effect"), "Question: " + g("question")
    if cls == "d":
        return rid, loc, g("behaviour"), "kept", "kept", "", g("why")
    return rid, loc, "", g("simc++"), g("simc++"), "", ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--differences", default=os.path.join(SRC, "docs", "FORTRAN_DIFFERENCES.md"))
    ap.add_argument("--decisions", default=os.environ.get(
        "SIMC_DECISIONS", os.path.join(SRC, "..", "..", "project_control", "DECISIONS.md")))
    ap.add_argument("--out", default=os.path.join(SRC, "docs", "translation", "06_catalogue.md"))
    a = ap.parse_args()
    rows = parse(a.differences)
    items = [(cls,) + norm(cls, h, d) for cls, h, d in rows]
    counts = {}
    for it in items:
        counts[it[0]] = counts.get(it[0], 0) + 1

    o = []
    o.append("# 6. Catalogue of Fortran bugs, quirks and deviations (generated)\n")
    o.append("Generated by `docs/translation/tools/gen_catalogue.py` from the class tables of "
             "[FORTRAN_DIFFERENCES.md](../FORTRAN_DIFFERENCES.md) (§2-§6: the single source that the code markers and the "
             "`fortran_diff` tests cite) and cross-checked against the finding ids of `project_control/DECISIONS.md` (§6.4). "
             "Do not edit by hand. The per-reaction measurements of the effect of the corrections (L2 in both modes) are "
             "in FORTRAN_DIFFERENCES.md §7-§17.\n")
    o.append("## 6.1 Classes\n")
    o.append("| class | meaning | entries |\n|---|---|---|")
    for c in ("a", "a-np", "b", "c", "d", "dev"):
        o.append("| %s | %s | %d |" % (c, CLASS_TEXT[c], counts.get(c, 0)))
    o.append("\nColumns: `id` (decision and finding id, `D-xxx Fn`; the decision text is in DECISIONS.md and the finding in "
             "`reference/P*.F*_report.md`), Fortran location (file:line), the Fortran behaviour, what SIMC++ does in the "
             "default (corrected) mode and with `--fortran-compat`, the effect on outputs, and the test (class a), the "
             "question (class b), the marker (class c) or the reason it is kept (class d).\n")
    o.append("## 6.2 The catalogue\n")
    titles = {"a": "Class a: clear Fortran bugs (corrected by default)", "a-np": "Class a-np",
              "b": "Class b: ambiguous, kept (the expert list)", "c": "Class c: acceptance mode (open)",
              "d": "Class d: faithful quirks (kept)", "dev": "Deliberate design deviations"}
    n = 0
    for c in ("a", "a-np", "b", "c", "d", "dev"):
        sel = [it for it in items if it[0] == c]
        if not sel:
            continue
        o.append("### %s\n" % titles[c])
        if c == "dev":
            o.append("| # | id | Fortran | SIMC++ (both modes) |\n|---|---|---|---|")
            for it in sel:
                n += 1
                o.append("| %d | %s | %s | %s |" % (n, it[1], it[2], it[4]))
        elif c == "d":
            o.append("| # | id | Fortran location | Fortran behaviour (kept in both modes) | why kept |\n|---|---|---|---|---|")
            for it in sel:
                n += 1
                o.append("| %d | %s | %s | %s | %s |" % (n, it[1], it[2], it[3], it[7]))
        else:
            o.append("| # | id | Fortran location | Fortran behaviour | default (corrected) mode | `--fortran-compat` | "
                     "effect | %s |\n|---|---|---|---|---|---|---|---|" % ("test" if c == "a" else "question / marker"))
            for it in sel:
                n += 1
                o.append("| %d | %s | %s | %s | %s | %s | %s | %s |" % ((n,) + it[1:]))
        o.append("")

    # the expert list
    o.append("## 6.3 The expert list\n")
    o.append("The class-b items are the open physics questions for the user and an expert (P15.X). Each keeps the Fortran "
             "behaviour in both modes. Together with the acceptance mode (class c, D-031 flag 1) and the Delta weight "
             "(D-048 F4: the doing_delta weight contains no cross section) they are the questions the translation could "
             "not answer.\n")
    o.append("| id | Fortran location | question |\n|---|---|---|")
    for it in items:
        if it[0] == "b":
            o.append("| %s | %s | %s |" % (it[1], it[2], it[7].replace("Question: ", "")))
    o.append("")

    # cross-check with DECISIONS.md
    o.append("## 6.4 Cross-check with the decisions\n")
    cat = "\n".join(" ".join(it[1:]) for it in items) + "\n" + open(a.differences, encoding="utf-8").read()
    if os.path.exists(a.decisions):
        dec = open(a.decisions, encoding="utf-8").read()
        blocks = re.split(r"^## (D-\d{3})", dec, flags=re.M)
        missing, checked = [], 0
        for k in range(1, len(blocks), 2):
            did, body = blocks[k], blocks[k + 1]
            if "finding" not in body.lower() and "class a" not in body.lower() and "quirk" not in body.lower():
                continue
            ids = sorted(set(re.findall(r"\b([FGTRS]\d{1,2}[a-z]?)\b", body)), key=lambda x: (x[0], int(re.sub(r"\D", "", x))))
            for fid in ids:
                checked += 1
                pat = re.compile(re.escape(did) + r"[^|\n]{0,40}\b" + re.escape(fid) + r"\b")
                alt = re.compile(r"\b" + re.escape(fid) + r"\b")
                if not pat.search(cat):
                    # the id may be listed under a range (F10-F12) or a combined id (F3/F9)
                    near = [l for l in cat.split("\n") if did in l and alt.search(l)]
                    if not near:
                        missing.append((did, fid))
        o.append("Every finding id (`F`, `G`, `T`, `R`, `S` + number) named in a DECISIONS.md entry about findings was "
                 "searched in FORTRAN_DIFFERENCES.md together with its decision number: %d ids checked, %d without an "
                 "entry of their own.\n" % (checked, len(missing)))
        if missing:
            o.append("Ids without an entry of their own (most are documentation-only findings, class d, described in the "
                     "decision text, or ids of the provisional numbering that a later decision superseded, e.g. D-056 R-ids "
                     "→ D-057 F-ids; see the decision for each):\n")
            o.append("| decision | finding ids |\n|---|---|")
            byd = {}
            for d_, f_ in missing:
                byd.setdefault(d_, []).append(f_)
            for d_ in sorted(byd):
                o.append("| %s | %s |" % (d_, ", ".join(byd[d_])))
            o.append("")
    else:
        o.append("(DECISIONS.md not found: cross-check skipped.)\n")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(o) + "\n")
    print("wrote %s: %d entries (%s)" % (a.out, len(items), ", ".join("%s %d" % kv for kv in sorted(counts.items()))))


if __name__ == "__main__":
    sys.exit(main())
